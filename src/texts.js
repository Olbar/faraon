export function getAllVisibleInterfaceTexts() {
  const texts = [
    ...Object.values(UI_TEXT),
    ...Object.values(APP_TEXT)
      .filter((value) => typeof value === "string")
      .flatMap((value) => [value]),
    ...getAllAppMessageSamples(),
    ...Object.values(CONTROL_LABELS),
    ...TUTORIAL_STEPS.flatMap((step) => [step.title, step.text]),
    ...DIFFICULTIES.flatMap((difficulty) => [
      difficulty.name,
      difficulty.epithet,
      difficulty.description,
    ]),
    ...ROOMS.flatMap((room) => [
      room.name,
      room.subtitle,
      room.hint,
      room.description,
      room.puzzle.solvedText,
      room.puzzle.rewardName,
      ...(room.finalGate
        ? [room.finalGate.name, room.finalGate.description]
        : []),
      ...room.items.flatMap((item) => [item.name, item.description]),
    ]),
    ...ACHIEVEMENTS.flatMap((achievement) => [
      achievement.name,
      achievement.description,
      achievement.reward,
    ]),
    STORY.prologue,
    STORY.ending,
    STORY.endingPerfect,
    ...getAllDynamicMessageSamples(),
  ];

  return [...new Set(texts.filter((text) => typeof text === "string" && text.trim()))];
}

